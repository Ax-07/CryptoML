"""P3 live-only prediction capture with local hash-chained append-only journal.

Reads Binance USDT-M public Klines for last CLOSED bars (not historical
backfill), produces H2/H6 predictions before next M5 close, records a single
four-asset time-aligned batch. Requires frozen activation and model hashes.

IMPORTANT: local journal alone does not prove independent timestamps or
non-tampering. An external trusted timestamp/append-only archive is REQUIRED
before the experiment can be certified prospective. No performance scoring.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from ingestion.schema import normalize_klines
from mlpipeline.confidence_diagnostics import decision_and_margin
from mlpipeline.features import (
    FEATURE_COLUMNS, build_symbol_features, feature_matrix, join_market_context,
)
from mlpipeline.prospective_protocol import ASSETS, _date, _iso, _canonical, _sha, verify, verify_activation
from mlpipeline.trainer import _class_probs

API = "https://fapi.binance.com/fapi/v1/klines"
LIMIT = 120
MAX_ARRIVAL_SECONDS = 270  # strict: do not accept a row near next close


def fetch_latest_closed(symbol: str, *, now: datetime) -> pd.DataFrame:
    if symbol not in ASSETS:
        raise ValueError("Seen-only symbol required")
    q=urllib.parse.urlencode({"symbol":symbol,"interval":"5m","limit":LIMIT})
    req=urllib.request.Request(API+"?"+q,headers={"User-Agent":"CryptoML-P3-research/1"})
    with urllib.request.urlopen(req,timeout=12) as response:
        raw=json.loads(response.read())
    if not isinstance(raw,list):
        raise ValueError("Exchange returned no kline list")
    candles=normalize_klines(raw,symbol=symbol,source="rest",as_of=now)
    if len(candles)<65:
        raise ValueError("Not enough closed M5 bars")
    return candles


def latest_common_features(candles: dict[str,pd.DataFrame], *,now:datetime):
    if set(candles)!=set(ASSETS):
        raise ValueError("Four seen assets only")
    # Guard the raw CLOSED-bar timestamps before any BTC/ETH-context join.
    # Otherwise a lagging asset first surfaces as a misleading missing-feature
    # error rather than the real cross-asset synchronization failure.
    last_closes = []
    for sym in ASSETS:
        frame = candles[sym]
        if frame.empty or "bar_close_at" not in frame.columns:
            raise ValueError(f"Missing closed M5 candles: {sym}")
        last_closes.append(pd.Timestamp(frame["bar_close_at"].iloc[-1]))
    if len(set(last_closes)) != 1:
        raise ValueError("Candles not closed and timestamp-aligned across assets")
    features={sym:build_symbol_features(candles[sym]) for sym in ASSETS}
    rows=[]
    for sym in ASSETS:
        ctx=join_market_context(features[sym],features["BTCUSDT"],features["ETHUSDT"])
        tail=ctx.iloc[-1:].copy()
        if not np.isfinite(tail[FEATURE_COLUMNS].to_numpy(dtype=float)).all():
            raise ValueError(f"Incomplete causal features: {sym}")
        rows.append(tail)
    out=pd.concat(rows,ignore_index=True)
    if out.bar_close_at.nunique()!=1 or out.symbol.nunique()!=4:
        raise ValueError("Candles not closed and timestamp-aligned across assets")
    close=out.bar_close_at.iloc[0].to_pydatetime()
    lag=(now-close).total_seconds()
    if not (0<=lag<MAX_ARRIVAL_SECONDS):
        raise ValueError("Late, stale, or future candle: refuse retroactive forecast")
    return out,close


def _load_packs(activation:dict):
    loaded={}
    for key,h in (("H2",2),("H6",6)):
        # NEVER deserialize a downloaded/untrusted pickle/joblib artifact.
        # These files must be generated by this project and operator-reviewed.
        path=Path(activation["artifact_paths_at_activation"][key])
        pack=joblib.load(path)
        if (pack.get("horizon_bars")!=h or pack.get("features")!=list(FEATURE_COLUMNS)
                or pack.get("feature_schema_version")!="features_v1"
                or pack.get("label_schema_version")!="vol_scaled_v1"
                or np.asarray(pack.get("train_prior_counts")).shape!=(3,)):
            raise ValueError(f"Invalid model pack metadata: {key}")
        expected=activation["threshold_policy"]["training_provenance"][key]
        if pack["train_prior_counts"]!=expected["train_prior_counts"]:
            raise ValueError(f"Pack prior mismatch: {key}")
        loaded[key]=pack
    return loaded


def make_forecasts(rows:pd.DataFrame, packs:dict, activation:dict)->dict:
    X=feature_matrix(rows)
    hour=int(rows.bar_close_at.iloc[0].hour)
    key="12-17_UTC" if 12<=hour<18 else "all_day_UTC"
    result={}
    for name in ("H2","H6"):
        pack=packs[name]
        probs=_class_probs(pack["estimator"],X)
        prior=np.asarray(pack["train_prior_counts"],dtype=int)
        predicted,margins=decision_and_margin(probs,prior,alpha=1.0)
        cutoff=activation["threshold_policy"]["thresholds"][name][key]
        result[name]={
            str(sym):{
                "raw_probabilities_down_neutral_up":[float(x) for x in probs[idx]],
                "raw_decision":int(predicted[idx]),
                "margin":float(margins[idx]),
                "threshold":float(cutoff),
                "selected_direction":int(predicted[idx]) if predicted[idx]!=1 and margins[idx]>=cutoff else None,
                "policy_cohort":key,
            } for idx,sym in enumerate(rows.symbol)
        }
    return result


def append_one_batch(root:Path, *, close:datetime, now:datetime, forecasts:dict):
    registration=verify(root)
    activation=verify_activation(root)
    if not (_date(registration["prospective_start_utc"])<=now
            <_date(registration["prospective_end_exclusive_utc"])):
        raise ValueError("Not inside frozen forward collection window")
    if close>=now or not (0<=(now-close).total_seconds()<MAX_ARRIVAL_SECONDS):
        raise ValueError("Stale/retroactive bar: cannot append")
    if set(forecasts)!={"H2","H6"} or any(set(forecasts[h])!=set(ASSETS) for h in forecasts):
        raise ValueError("Invalid aligned 4-asset forecasts")
    path=root/"predictions.jsonl"
    previous="0"*64
    last=None
    if path.exists():
        with path.open("rb") as f:
            for line in f:
                entry=json.loads(line)
                signed={k:v for k,v in entry.items() if k!="entry_sha256"}
                if (entry["previous_sha256"]!=previous
                        or _sha(_canonical(signed))!=entry["entry_sha256"]):
                    raise ValueError("Local append-only chain corruption")
                if last is not None and _date(entry["bar_close_utc"])<=last:
                    raise ValueError("Journal timestamps not increasing")
                last=_date(entry["bar_close_utc"])
                previous=entry["entry_sha256"]
    if last is not None and close<=last:
        raise ValueError("Duplicate/older bar: refusing backfill")
    record={
        "bar_close_utc":_iso(close),
        "recorded_at_utc":_iso(now),
        "activation_sha256":(root/"activation.sha256").read_text("ascii").strip(),
        "previous_sha256":previous,
        "forecasts":forecasts,
    }
    record["entry_sha256"]=_sha(_canonical(record))
    path.parent.mkdir(parents=True,exist_ok=True)
    # Single-writer only. Must run once per five minutes, not concurrent.
    fd=os.open(str(path),os.O_APPEND|os.O_CREAT|os.O_WRONLY,0o600)
    try:
        with os.fdopen(fd,"ab") as stream:
            stream.write(_canonical(record))
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        raise
    return record


def capture_once(root:Path):
    registration=verify(root)
    activation=verify_activation(root)
    now=datetime.now(timezone.utc)
    if not (_date(registration["prospective_start_utc"])<=now
            <_date(registration["prospective_end_exclusive_utc"])):
        raise ValueError("Not within collection window")
    # System clock and network latency must be independently monitored.
    packs=_load_packs(activation)
    candles={sym:fetch_latest_closed(sym,now=now) for sym in ASSETS}
    stamp=datetime.now(timezone.utc)
    rows,close=latest_common_features(candles,now=stamp)
    forecasts=make_forecasts(rows,packs,activation)
    # Recheck wallclock before append; prevents late inference from appearing on time.
    actual=datetime.now(timezone.utc)
    record=append_one_batch(root,close=close,now=actual,forecasts=forecasts)
    print("Local forecast batch captured",record["bar_close_utc"],record["entry_sha256"])
    print("WARNING: independent timestamp anchoring is NOT implemented")


def main():
    p=argparse.ArgumentParser(description="P3 live-only single M5 batch (NO scoring/backfill)")
    p.add_argument("--root",type=Path,required=True)
    args=p.parse_args()
    capture_once(args.root)


if __name__=="__main__":
    main()
